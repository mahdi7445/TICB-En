def describe(module: str, verdict: dict = None, cfg_line: str = "") -> str:
    """متن کامل توضیح استراتژی + وضعیت بک‌تست (خودکار از lowtf_verdicts.json)."""
    import ladder_catalog as lc
    if module in lc.CANDLE:
        d = _CN
    else:
        d = DESC.get(module, "")
    out = [d]
    v = verdict or {}
    if v:
        reasons = ", ".join(v.get("fail_reasons") or []) or "-"
        out.append(f"\nنتیجه‌ی بک‌تست ({v.get('tf', '?')}): وضعیت {v.get('verdict')} | معامله {v.get('n')} | میانگین {v.get('avg_r', 0):+.2f}R | "
                   f"PF {v.get('pf', 0):.2f} | win {v.get('win', 0):.0f}% | t={v.get('t', 0):.1f} | train {v.get('train_r', 0):+.2f}R / test {v.get('test_r', 0):+.2f}R | "
                   f"بیشینه دراودان {v.get('max_dd_r', 0):.0f}R | نمادهای مثبت {v.get('symbols_positive', 0) * 100:.0f}% | علت رد: {reasons}")
        out.append(f"بهترین واریانت: فیلتر «{FILTERS.get(v.get('filter', 'none'), v.get('filter'))}» + {STOPS.get(v.get('stop', 'nat'), v.get('stop'))}.")
    if cfg_line:
        out.append(cfg_line)
    return "\n".join(x for x in out if x)
