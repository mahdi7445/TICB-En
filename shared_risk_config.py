def format_signal_price(value: float) -> str:
    """فرمت مشترکِ نمایش قیمت در متن سیگنال‌ها (بدون علامت $) - قبلاً candle_engine.py
    (_fmt_price، با جداکننده‌ی هزارگان و رقم اعشار پویا بر اساس log10) و bot.py
    (format_signal_price، بدون جداکننده‌ی هزارگان و با آستانه‌های ثابت رقم اعشار) دو
    پیاده‌سازیِ متفاوت داشتن - یعنی مثلاً یک قیمت مثل 67543.21 در کانال VIP با کاما
    («67,543.21») و در سیگنال‌های آلت‌کوین (که TOP30 هم می‌تونه شامل بیت‌کوین/اتریوم/کوین‌های
    گران‌قیمت باشه) بدون کاما («67543.21») نشون داده می‌شد - ظاهر ناهماهنگ بین دو رباتی که
    به یک کانال پست می‌کنن. الان هر دو از همین یک تابع استفاده می‌کنن: برای قیمت‌های ≥ ۱ با
    جداکننده‌ی هزارگان و ۲ رقم اعشار؛ برای زیر ۱ دلار، رقم اعشار پویا بر اساس بزرگیِ خودِ
    قیمت (حداقل ۳ رقم معنادار) - نه آستانه‌ی ثابت - تا یک آلت‌کوینِ خیلی کم‌قیمت هم هیچ‌وقت
    به 0.00/0.0000 گرد نشه."""
    try:
        v = float(value)
    except (TypeError, ValueError):
        return str(value)
    if v == 0:
        return "0.00"
    av = abs(v)
    if av >= 1:
        return f"{v:,.2f}"
    decimals = min(12, max(2, -int(math.floor(math.log10(av))) + 3))
    return f"{v:.{decimals}f}"
