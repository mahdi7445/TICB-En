"""
تنظیمات مشترک سیستم ریسک/ریوارد «RiskRivard» بین candle_engine.py و subscription_bot.py.

⚠️ چرا این فایل جدا شد: قبلاً وزن‌های W1..W_RUNNER و RR_TARGETS و منطق compute_final_r
داخل candle_engine.py تعریف می‌شدن، و subscription_bot.py یک کپیِ دستیِ جداگانه از همون
منطق داشت (فقط برای نمایش زنده‌ی "نتیجه‌ی بانک‌شده تا این لحظه" روی معاملات باز، بدون
نیاز به import کردن کل candle_engine.py که وابستگی‌های سنگین pandas/matplotlib/mplfinance
داره - در حالی که requirements ی subscription_bot.py فقط requests است).

مشکل این کپی دستی: یک کامنت هشدار می‌گفت «این وزن‌ها باید همیشه دقیقاً هماهنگ بمونن» - یعنی
هر تغییری توی یکی، باید دستی یادت بمونه توی اون یکی هم اعمال کنی، وگرنه نتایج /results با
نتایج واقعیِ کانال فرق می‌کنه بدون این‌که متوجه بشی. این فایل بدون هیچ وابستگی سنگینی
(فقط Python خالص) اون منطق رو یک‌جا نگه می‌داره، و هر دو اسکریپت از همینجا import می‌کنن -
پس دیگه هیچ‌وقت امکان drift بین دوتا نداره.

اگه بخوای سیستم ریسک/ریوارد رو تغییر بدی (مثلاً درصدهای بسته‌شدن یا سطوح تارگت)، فقط همینجا
عوض کن - هر دو اسکریپت خودکار هماهنگ می‌مونن.
"""

from typing import Any, Dict

# سطوح تارگت بر حسب واحد R (نه درصد مساوی - طبق طرح RiskRivard روی ۱R/۲R/۴R/۶R)
RR_TARGETS = [1, 2, 4, 6]
TARGET_LABELS = {1: "Target 1", 2: "Target 2", 4: "Target 3", 6: "Target 4"}

# 🔴 لیست تایم‌فریم‌های معتبر - منبع مشترک بین subscription_bot.py (که موقع ثبت هر سیگنال
# دستی/تگ‌شده/فوروارد‌شده، تایم‌فریم اعلام‌شده رو با همین لیست اعتبارسنجی می‌کنه) و
# candle_engine.py (که همین برچسب‌ها رو در TIMEFRAMES خودش تعریف کرده). چرا اینجا: طبق
# درخواست صریح - «هیچ سیگنالی، حتی سیگنال دستی، بدون تایم‌فریم مشخص وجود نداره» - پس این
# اعتبارسنجی باید در همون لحظه‌ی ورودی (subscription_bot.py، جایی که ادمین یا فوروارد
# پردازش می‌شه) اتفاق بیفته، نه فقط بعداً در candle_engine.py؛ ولی subscription_bot.py
# عمداً سبک نگه داشته شده (بدون pandas/mplfinance) و TIMEFRAMES کامل (با td_interval و
# bar_seconds) رو import نمی‌کنه - فقط همین لیست برچسب‌ها لازمه. اگه یک TF جدید به
# TIMEFRAMES در candle_engine.py اضافه/حذف بشه، باید دقیقاً همینجا هم به‌روز بشه - و برای
# جلوگیری از drift، candle_engine.py هنگام بالا اومدن با یک assert این دو رو با هم چک
# می‌کنه (پایین‌تر در همون فایل).
VALID_TIMEFRAME_LABELS = {"1M", "5M", "15M", "1H", "4H"}

# درصدهای بسته‌شدن در هر مرحله - همه‌شون درصدی از حجم اصلی/کل پوزیشن‌اند (نه از باقی‌مانده)
W1 = 0.20   # Target 1 (1R)
W2 = 0.30   # Target 2 (2R)
W3 = 0.15   # Target 3 (4R)
W4 = 0.10   # Target 4 (6R)
W_RUNNER = 0.25  # Runner - باقی‌مانده بعد از Target 4، با تریلینگ ۱.۵R باز می‌مونه
TRAILING_R_MULT = 1.5  # فاصله‌ی تریلینگ‌استاپ رانر از peak price، بر حسب واحد R اولیه‌ی معامله

assert abs((W1 + W2 + W3 + W4 + W_RUNNER) - 1.0) < 1e-9, "جمع درصدها باید دقیقاً ۱۰۰٪ باشه"


def compute_final_r(trade: Dict[str, Any]) -> float:
    """تخمین نتیجه‌ی نهایی معامله بر حسب R، بر اساس درصد بسته‌شدن پوزیشن (از کل) در هر مرحله
    و محل واقعی حد ضرر در همون مرحله. برای رانر که قیمت خروج دقیقش از قبل معلوم نیست (تریلینگ
    باز است)، یک تخمین محافظه‌کارانه در سطح Target 4 (6R) در نظر گرفته می‌شود - نه بیشتر."""
    hit = trade["hit"]
    if not hit["1"]:
        return -1.0  # هیچ تارگتی نخورده، کل پوزیشن با ضرر کامل (حد ضرر اولیه) بسته شده
    if not hit["2"]:
        # بعد از T1: ۲۰٪ با ۱R سود بانک شده، ۸۰٪ باقی‌مانده با SL روی Entry (ریسک‌فری) بسته شده
        return W1 * 1 + (1 - W1) * 0.0
    if not hit["4"]:  # یعنی به Target 3 (سطح 4R) نرسیده
        # بعد از T2: ۲۰٪@1R + ۳۰٪@2R بانک شده، ۵۰٪ باقی‌مانده با SL روی T1 (1R) بسته شده
        return W1 * 1 + W2 * 2 + (1 - W1 - W2) * 1.0
    if not hit["6"]:  # یعنی به Target 4 (سطح 6R) نرسیده
        # بعد از T3: ۲۰٪@1R + ۳۰٪@2R + ۱۵٪@4R بانک شده، ۳۵٪ باقی‌مانده با SL روی T2 (2R) بسته شده
        return W1 * 1 + W2 * 2 + W3 * 4 + (1 - W1 - W2 - W3) * 2.0
    # به Target 4 (6R) رسیده: ۲۰+۳۰+۱۵+۱۰=۷۵٪ بانک شده + ۲۵٪ Runner با تخمین محافظه‌کارانه در 6R
    return W1 * 1 + W2 * 2 + W3 * 4 + W4 * 6 + W_RUNNER * 6.0
