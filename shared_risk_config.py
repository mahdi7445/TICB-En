# سطوح تارگت بر حسب واحد R (نه درصد مساوی - طبق طرح RiskRivard روی ۱R/۲R/۴R/۶R)
RR_TARGETS = [1, 2, 4, 6]
TARGET_LABELS = {1: "Target 1", 2: "Target 2", 4: "Target 3", 6: "Target 4"}

# 🔴 لیست تایم‌فریم‌های معتبر - منبع مشترک بین subscription_bot.py (که موقع ثبت هر سیگنال
# دستی/تگ‌شده/فوروارد‌شده، تایم‌فریم اعلام‌شده رو با همین لیست اعتبارسنجی می‌کنه) و
