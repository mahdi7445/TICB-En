# جلوگیری از drift، candle_engine.py هنگام بالا اومدن با یک assert این دو رو با هم چک
# می‌کنه (پایین‌تر در همون فایل).
VALID_TIMEFRAME_LABELS = {"1M", "5M", "15M", "1H", "4H"}

# درصدهای بسته‌شدن در هر مرحله - همه‌شون درصدی از حجم اصلی/کل پوزیشن‌اند (نه از باقی‌مانده)
W1 = 0.20   # Target 1 (1R)
W2 = 0.30   # Target 2 (2R)
W3 = 0.15   # Target 3 (4R)
W4 = 0.10   # Target 4 (6R)
W_RUNNER = 0.25  # Runner - باقی‌مانده بعد از Target 4، با تریلینگ ۱.۵R باز می‌مونه
TRAILING_R_MULT = 1.5  # فاصله‌ی تریلینگ‌استاپ رانر از peak price، بر حسب واحد R اولیه‌ی معامله

assert abs((W1 + W2 + W3 + W4 + W_RUNNER) - 1.0) < 1e-9, "جمع درصدها باید دقیقاً ۱۰۰٪ باشه"


def compute_final_r(trade: Dict[str, Any]) -> float:
    """نتیجه‌ی نهایی معامله بر حسب R، بر اساس درصد بسته‌شدن پوزیشن (از کل) در هر مرحله
    و محل واقعی حد ضرر در همون مرحله.

    🔴 اضافه شد: final_r_exact - وقتی معامله با یک مکانیزمی غیر از توالی استاندارد
    SL/تارگت بسته می‌شه (فعلاً فقط یک مورد: بسته‌شدنِ اجباری به‌خاطر یک سیگنال مخالف -
    candle_engine.py::_force_close_trade)، کل ۱۰۰٪ پوزیشن (یا باقی‌مانده‌اش) دقیقاً روی
    قیمت بازار همون لحظه بسته می‌شه - نه روی یکی از سطوح ثابتِ فرضیِ این تابع (Entry/
    Target1/Target2). فرمول‌های زیر (hit["1"]/hit["2"]/...) فرض می‌کنن باقی‌مانده‌ی
    پوزیشن دقیقاً روی همون سطح ثابت بسته می‌شه - که برای SL/بریک‌ایون/تارگت‌های واقعی
    همیشه درسته (چون واقعاً همونجا working_sl گذاشته شده)، ولی برای یک بستنِ اجباریِ
    زودهنگام (قیمتِ بازار، نه یک سطح از پیش‌تعیین‌شده) کاملاً اشتباهه: قبلاً برای مثال
    یک معامله‌ای که هنوز به Target 1 نرسیده بود ولی با سود یا ضررِ جزئیِ متفاوتی force
    بسته می‌شد، همیشه دقیقاً -1.0R (انگار درست خورده به حد ضرر کامل) گزارش می‌شد - بدون
    توجه به قیمتِ واقعیِ بسته‌شدن؛ به‌همین ترتیب برای مراحل بعدی هم عددِ نمایش‌داده‌شده
    (در پیام «⚠️ TRADE CLOSED»، trade_history.json، /results، /history، گزارش روزانه/
    هفتگی، و equity chart) با نتیجه‌ی واقعیِ کاربر فرق داشت. وقتی caller این مقدارِ
    دقیقِ از پیش‌محاسبه‌شده رو مستقیم ست کنه (final_r_exact)، همون به‌جای فرمولِ فرضیِ
    زیر مستقیماً برگردونده می‌شه - برای همه‌ی مسیرهای دیگه (که این فیلد رو ست نمی‌کنن)
    هیچ تغییری در رفتار نیست."""
    if trade.get("final_r_exact") is not None:
        return trade["final_r_exact"]
    hit = trade["hit"]
    if not hit["1"]:
        return -1.0  # هیچ تارگتی نخورده، کل پوزیشن با ضرر کامل (حد ضرر اولیه) بسته شده
    if not hit["2"]:
        # بعد از T1: ۲۰٪ با ۱R سود بانک شده، ۸۰٪ باقی‌مانده با SL روی Entry (ریسک‌فری) بسته شده
        return W1 * 1 + (1 - W1) * 0.0
    if not hit["4"]:  # یعنی به Target 3 (سطح 4R) نرسیده
        # بعد از T2: ۲۰٪@1R + ۳۰٪@2R بانک شده، ۵۰٪ باقی‌مانده با SL روی T1 (1R) بسته شده
        return W1 * 1 + W2 * 2 + (1 - W1 - W2) * 1.0
    if not hit["6"]:  # یعنی به Target 4 (سطح 6R) نرسیده
        # بعد از T3: ۲۰٪@1R + ۳۰٪@2R + ۱۵٪@4R بانک شده، ۳۵٪ باقی‌مانده با SL روی T2 (2R) بسته شده
        return W1 * 1 + W2 * 2 + W3 * 4 + (1 - W1 - W2 - W3) * 2.0
    # به Target 4 (6R) رسیده: ۲۰+۳۰+۱۵+۱۰=۷۵٪ بانک شده + ۲۵٪ Runner. اگه رانر واقعاً بسته
    # شده، runner_r دقیقِ واقعی استفاده می‌شه؛ وگرنه (رانر هنوز باز) 6.0 به‌عنوان تخمین
    # محافظه‌کارانه‌ی موقت.
    runner_component = trade.get("runner_r")
    if runner_component is None:
        runner_component = 6.0
    return W1 * 1 + W2 * 2 + W3 * 4 + W4 * 6 + W_RUNNER * runner_component


